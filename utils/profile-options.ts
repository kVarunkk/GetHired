/**
 * Filter options: the common ones first, then any other values profiles hold,
 * with each name once whatever its case or spacing.
 */
export function mergeOptions(common: string[], found: string[]): string[] {
  const seen = new Set<string>();
  return [...common, ...found].flatMap((value) => {
    const name = value?.trim();
    // "|" separates the values of a filter in the URL.
    if (!name || name.includes("|")) return [];
    const key = name.toLowerCase();
    if (seen.has(key)) return [];
    seen.add(key);
    return [name];
  });
}
