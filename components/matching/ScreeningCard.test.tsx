import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { act, render, screen, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import toast from "react-hot-toast";
import { APPLICATION, JOB_POST, screeningResultOf } from "@/test/utils/matching";
import type { ScreeningView } from "@/helpers/matching/screening-view";
import ScreeningCard from "./ScreeningCard";

const handleEntitlement = vi.fn();
vi.mock("@/hooks/useEntitlementError", () => ({
  useEntitlementError: () => ({ handle: handleEntitlement, show: vi.fn(), dialog: <div data-testid="upgrade" /> }),
}));
vi.mock("react-hot-toast", () => ({ default: { error: vi.fn(), success: vi.fn() } }));

const fetchMock = vi.fn();
const QUESTIONS = JOB_POST.questions!;
const BACKFILL = `/api/company/job-posts/${JOB_POST.id}/screen`;
const POLL = `/api/company/applications/${APPLICATION.id}/screening`;
const FOOTNOTE = /Generated by AI.*Verify before deciding\./;

const screeningOf = (overrides: Partial<ScreeningView> = {}): ScreeningView => ({
  id: "f1000000-0000-4000-8000-000000000001",
  application_id: APPLICATION.id,
  status: "completed",
  fit_score: 82,
  recommendation: "yes",
  result: screeningResultOf({ flags: ["Notice period is 90 days"] }),
  error_code: null,
  completed_at: "2026-10-15T00:00:00Z",
  updated_at: "2026-10-15T00:00:00Z",
  ...overrides,
});

const renderCard = (screening: ScreeningView | null) =>
  render(
    <ScreeningCard
      applicationId={APPLICATION.id}
      jobPostId={JOB_POST.id}
      questions={QUESTIONS}
      screening={screening}
    />,
  );

const inProgress = (status: "queued" | "processing") =>
  screeningOf({ status, fit_score: null, recommendation: null, result: null, completed_at: null });

beforeEach(() => {
  vi.clearAllMocks();
  handleEntitlement.mockImplementation(async (res: Response) => res.status === 402);
  vi.stubGlobal("fetch", fetchMock);
});
afterEach(() => {
  vi.useRealTimers();
  vi.unstubAllGlobals();
});

describe("ScreeningCard (MT-TEST-006)", () => {
  it.each(["queued", "processing"] as const)("shows Screening… while %s", (status) => {
    vi.useFakeTimers();
    renderCard(inProgress(status));

    expect(screen.getByText("Screening…")).toBeInTheDocument();
    expect(screen.queryByText(FOOTNOTE)).not.toBeInTheDocument();
  });

  it("shows a completed screening", () => {
    renderCard(screeningOf());

    expect(screen.getByText("82 · Strong")).toBeInTheDocument();
    expect(screen.getByText("Yes")).toBeInTheDocument();
    expect(screen.getByText(screeningResultOf().summary)).toBeInTheDocument();
    expect(screen.getByText("Notice period is 90 days")).toBeInTheDocument();
    expect(screen.getByText(FOOTNOTE)).toBeInTheDocument();

    const table = screen.getByRole("table", { name: "Must-haves" });
    const rows = within(table).getAllByRole("row").slice(1);
    expect(rows).toHaveLength(screeningResultOf().must_have_coverage.length);
    expect(rows[0]).toHaveTextContent("4+ years of React");
    expect(rows[0]).toHaveTextContent("Led 5 years of React work");
    expect(rows[2]).toHaveTextContent("Partial");
  });

  it("collapses the answer feedback until it's opened", async () => {
    renderCard(screeningOf());

    const toggle = screen.getByRole("button", { name: /Answer feedback/ });
    expect(toggle).toHaveAttribute("aria-expanded", "false");
    expect(screen.queryByText("Concrete numbers and approach.")).not.toBeInTheDocument();

    await userEvent.click(toggle);

    expect(toggle).toHaveAttribute("aria-expanded", "true");
    expect(screen.getByText("Concrete numbers and approach.")).toBeInTheDocument();
    expect(screen.getByText(QUESTIONS[0])).toBeInTheDocument();
  });

  it("uses no red or green colouring for the candidate", () => {
    const { container } = renderCard(screeningOf({ fit_score: 30, recommendation: "no" }));

    expect(container.innerHTML).not.toMatch(/destructive|success|text-red|text-green|bg-red|bg-green/);
  });

  it("offers a retry for a failed screening, which re-queues it", async () => {
    fetchMock.mockResolvedValue(Response.json({ queued: 1 }));
    renderCard(screeningOf({ status: "failed", result: null, fit_score: null, error_code: "model_error" }));

    await userEvent.click(screen.getByRole("button", { name: "Retry" }));

    expect(fetchMock).toHaveBeenCalledWith(BACKFILL, expect.objectContaining({ method: "POST" }));
    expect(await screen.findByText("Screening…")).toBeInTheDocument();
  });

  it("opens the upgrade dialog from Upgrade to screen when the allowance is still used up", async () => {
    fetchMock.mockResolvedValue(Response.json({ code: "entitlement" }, { status: 402 }));
    renderCard(screeningOf({ status: "skipped_quota", result: null, fit_score: null }));

    await userEvent.click(screen.getByRole("button", { name: "Upgrade to screen" }));

    expect(fetchMock).toHaveBeenCalledWith(BACKFILL, expect.objectContaining({ method: "POST" }));
    expect(handleEntitlement).toHaveBeenCalled();
    expect(screen.queryByText("Screening…")).not.toBeInTheDocument();
    expect(screen.getByTestId("upgrade")).toBeInTheDocument();
  });

  it("keeps a stale result with a banner and a Re-screen button", async () => {
    fetchMock.mockResolvedValue(Response.json({ queued: 1 }));
    renderCard(screeningOf({ status: "stale" }));

    expect(screen.getByText(/Job changed since this screening/)).toBeInTheDocument();
    expect(screen.getByText(screeningResultOf().summary)).toBeInTheDocument();

    await userEvent.click(screen.getByRole("button", { name: "Re-screen" }));

    expect(fetchMock).toHaveBeenCalledWith(BACKFILL, expect.objectContaining({ method: "POST" }));
    expect(await screen.findByText("Screening…")).toBeInTheDocument();
  });

  it("toasts when a re-queue fails", async () => {
    fetchMock.mockResolvedValue(Response.json({ error: "Couldn't queue." }, { status: 500 }));
    renderCard(screeningOf({ status: "failed", result: null, fit_score: null }));

    await userEvent.click(screen.getByRole("button", { name: "Retry" }));

    expect(toast.error).toHaveBeenCalledWith("Couldn't queue.");
  });

  it("offers to screen an application with no screening", async () => {
    fetchMock.mockResolvedValue(Response.json({ queued: 1 }));
    renderCard(null);

    await userEvent.click(screen.getByRole("button", { name: "Screen now" }));

    expect(fetchMock).toHaveBeenCalledWith(BACKFILL, expect.objectContaining({ method: "POST" }));
  });
});

describe("ScreeningCard polling (MT-REQ-007)", () => {
  it("polls every 5 seconds while queued and shows the result when it completes", async () => {
    vi.useFakeTimers();
    fetchMock
      .mockResolvedValueOnce(Response.json({ screening: inProgress("processing") }))
      .mockResolvedValueOnce(Response.json({ screening: screeningOf() }));
    renderCard(inProgress("queued"));

    await act(() => vi.advanceTimersByTimeAsync(4_999));
    expect(fetchMock).not.toHaveBeenCalled();

    await act(() => vi.advanceTimersByTimeAsync(1));
    expect(fetchMock).toHaveBeenCalledWith(POLL, expect.anything());
    expect(screen.getByText("Screening…")).toBeInTheDocument();

    await act(() => vi.advanceTimersByTimeAsync(5_000));
    expect(screen.getByText("82 · Strong")).toBeInTheDocument();

    await act(() => vi.advanceTimersByTimeAsync(30_000));
    expect(fetchMock).toHaveBeenCalledTimes(2);
  });

  it("stops polling after 2 minutes", async () => {
    vi.useFakeTimers();
    fetchMock.mockImplementation(async () => Response.json({ screening: inProgress("queued") }));
    renderCard(inProgress("queued"));

    await act(() => vi.advanceTimersByTimeAsync(120_000));
    const calls = fetchMock.mock.calls.length;
    expect(calls).toBeLessThanOrEqual(24);

    await act(() => vi.advanceTimersByTimeAsync(60_000));
    expect(fetchMock).toHaveBeenCalledTimes(calls);
    expect(screen.getByText(/taking longer than usual/i)).toBeInTheDocument();
  });

  it("doesn't poll a completed screening", async () => {
    vi.useFakeTimers();
    renderCard(screeningOf());

    await act(() => vi.advanceTimersByTimeAsync(30_000));

    expect(fetchMock).not.toHaveBeenCalled();
  });
});
