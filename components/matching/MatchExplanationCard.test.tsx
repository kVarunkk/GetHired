import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { render, screen, waitFor, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import toast from "react-hot-toast";
import { JOB_POST, explanationOf } from "@/test/utils/matching";
import { PUBLIC_APPLICANT } from "@/test/utils/recruiter";
import MatchExplanationCard from "./MatchExplanationCard";

const handleEntitlement = vi.fn();
vi.mock("@/hooks/useEntitlementError", () => ({
  useEntitlementError: () => ({ handle: handleEntitlement, show: vi.fn(), dialog: <div data-testid="upgrade" /> }),
}));
vi.mock("react-hot-toast", () => ({ default: { error: vi.fn(), success: vi.fn() } }));

const fetchMock = vi.fn();
const IDS = { jobPostId: JOB_POST.id, candidateId: PUBLIC_APPLICANT.id };
const FOOTNOTE = /Generated by AI from the candidate's profile and resume\. Verify before deciding\./;

beforeEach(() => {
  vi.clearAllMocks();
  handleEntitlement.mockImplementation(async (res: Response) => res.status === 402);
  vi.stubGlobal("fetch", fetchMock);
});
afterEach(() => vi.unstubAllGlobals());

describe("MatchExplanationCard (MT-REQ-003/004)", () => {
  it("lists strengths, gaps and conflicts", () => {
    render(
      <MatchExplanationCard
        {...IDS}
        explanation={explanationOf({ conflicts: ["Wants remote; job is onsite in Pune"] })}
      />,
    );

    const list = (name: string) =>
      within(screen.getByRole("region", { name })).getAllByRole("listitem").map((li) => li.textContent);
    expect(list("Strengths")).toEqual(explanationOf().strengths);
    expect(list("Gaps")).toEqual(explanationOf().gaps);
    expect(list("Conflicts")).toEqual(["Wants remote; job is onsite in Pune"]);
    expect(screen.getByText(explanationOf().summary)).toBeInTheDocument();
  });

  it("hides empty sections", () => {
    render(<MatchExplanationCard {...IDS} explanation={explanationOf({ gaps: [], conflicts: [] })} />);

    expect(screen.getByRole("region", { name: "Strengths" })).toBeInTheDocument();
    expect(screen.queryByRole("region", { name: "Gaps" })).not.toBeInTheDocument();
    expect(screen.queryByRole("region", { name: "Conflicts" })).not.toBeInTheDocument();
  });

  it.each([
    ["with an explanation", explanationOf()],
    ["without one", null],
  ])("always shows the AI footnote, %s", (_label, explanation) => {
    render(<MatchExplanationCard {...IDS} explanation={explanation} />);

    expect(screen.getByText(FOOTNOTE)).toBeInTheDocument();
  });

  it("fetches and renders an explanation on 'Why this match?'", async () => {
    fetchMock.mockResolvedValue(Response.json({ explanation: explanationOf({ summary: "Fresh summary" }) }));
    render(<MatchExplanationCard {...IDS} explanation={null} />);

    await userEvent.click(screen.getByRole("button", { name: "Why this match?" }));

    expect(await screen.findByText("Fresh summary")).toBeInTheDocument();
    expect(fetchMock).toHaveBeenCalledWith(
      "/api/company/matches/explain",
      expect.objectContaining({ method: "POST", body: JSON.stringify(IDS) }),
    );
    expect(screen.queryByRole("button", { name: "Why this match?" })).not.toBeInTheDocument();
  });

  it("opens the upgrade dialog on a 402", async () => {
    const res = Response.json({ code: "entitlement" }, { status: 402 });
    fetchMock.mockResolvedValue(res);
    render(<MatchExplanationCard {...IDS} explanation={null} />);

    await userEvent.click(screen.getByRole("button", { name: "Why this match?" }));

    await waitFor(() => expect(handleEntitlement).toHaveBeenCalledWith(res));
    expect(toast.error).not.toHaveBeenCalled();
    expect(screen.getByTestId("upgrade")).toBeInTheDocument();
  });

  it("toasts the error for other failures and lets you retry", async () => {
    fetchMock.mockResolvedValue(Response.json({ error: "Explaining this match took too long." }, { status: 504 }));
    render(<MatchExplanationCard {...IDS} explanation={null} />);

    await userEvent.click(screen.getByRole("button", { name: "Why this match?" }));

    await waitFor(() => expect(toast.error).toHaveBeenCalledWith("Explaining this match took too long."));
    expect(screen.getByRole("button", { name: "Why this match?" })).toBeEnabled();
  });

  it("toasts when the network fails", async () => {
    fetchMock.mockRejectedValue(new TypeError("Failed to fetch"));
    render(<MatchExplanationCard {...IDS} explanation={null} />);

    await userEvent.click(screen.getByRole("button", { name: "Why this match?" }));

    await waitFor(() => expect(toast.error).toHaveBeenCalled());
  });

  it("uses a short 'Why?' button in the compact variant", async () => {
    fetchMock.mockResolvedValue(Response.json({ explanation: explanationOf() }));
    render(<MatchExplanationCard {...IDS} explanation={null} compact />);

    await userEvent.click(screen.getByRole("button", { name: "Why?" }));

    expect(await screen.findByRole("region", { name: "Strengths" })).toBeInTheDocument();
  });
});
