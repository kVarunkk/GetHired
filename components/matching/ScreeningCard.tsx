"use client";

import { useEffect, useRef, useState } from "react";
import toast from "react-hot-toast";
import { ChevronDown, Info, Loader2 } from "lucide-react";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from "@/components/ui/table";
import MatchScoreBadge from "@/components/matching/MatchScoreBadge";
import { useEntitlementError } from "@/hooks/useEntitlementError";
import {
  RECOMMENDATION_LABELS,
  SCREENING_POLL_MAX_MS,
  SCREENING_POLL_MS,
} from "@/helpers/matching/config";
import type { ScreeningResult } from "@/helpers/matching/schemas";
import { isScreeningInProgress, type ScreeningView } from "@/helpers/matching/screening-view";
import { cn } from "@/utils/utils";

const FOOTNOTE =
  "Generated by AI from the application, profile and resume. It assists your decision and never changes a stage on its own. Verify before deciding.";

const MET_LABELS: Record<ScreeningResult["must_have_coverage"][number]["met"], string> = {
  yes: "Met",
  partial: "Partial",
  no: "Not met",
  unknown: "Unknown",
};

const QUALITY_LABELS: Record<ScreeningResult["answer_feedback"][number]["quality"], string> = {
  strong: "Strong",
  ok: "OK",
  weak: "Weak",
  missing: "Missing",
};

function List({ title, items }: { title: string; items: string[] }) {
  if (items.length === 0) return null;
  return (
    <section aria-label={title} className="flex flex-col gap-1">
      <h4 className="text-xs font-medium text-muted-foreground">{title}</h4>
      <ul className="list-disc pl-5 text-sm space-y-0.5">
        {items.map((item, i) => (
          <li key={i}>{item}</li>
        ))}
      </ul>
    </section>
  );
}

function AnswerFeedback({
  feedback,
  questions,
}: {
  feedback: ScreeningResult["answer_feedback"];
  questions: string[];
}) {
  const [open, setOpen] = useState(false);
  if (feedback.length === 0) return null;

  return (
    <section className="flex flex-col gap-2">
      <Button
        type="button"
        variant="ghost"
        size="sm"
        className="self-start -ml-2 text-muted-foreground"
        aria-expanded={open}
        onClick={() => setOpen((o) => !o)}
      >
        Answer feedback
        <ChevronDown className={cn("h-4 w-4 transition-transform", open && "rotate-180")} />
      </Button>
      {open && (
        <ol className="divide-y rounded-lg border">
          {feedback.map((entry) => (
            <li key={entry.question_index} className="flex flex-col gap-1 px-4 py-3">
              <div className="flex items-start justify-between gap-3">
                <p className="text-sm font-medium">
                  {questions[entry.question_index] ?? `Question ${entry.question_index + 1}`}
                </p>
                <Badge variant="outline" className="shrink-0">
                  {QUALITY_LABELS[entry.quality]}
                </Badge>
              </div>
              {entry.note && <p className="text-sm text-muted-foreground">{entry.note}</p>}
            </li>
          ))}
        </ol>
      )}
    </section>
  );
}

function Result({ result, questions }: { result: ScreeningResult; questions: string[] }) {
  return (
    <div className="flex flex-col gap-4">
      <p className="text-[15px] leading-7">{result.summary}</p>
      <List title="Strengths" items={result.strengths} />
      <List title="Gaps" items={result.gaps} />
      {result.must_have_coverage.length > 0 && (
        <section className="flex flex-col gap-1">
          <h4 className="text-xs font-medium text-muted-foreground">Must-haves</h4>
          <div className="overflow-x-auto rounded-lg border">
            <Table aria-label="Must-haves">
              <TableHeader>
                <TableRow>
                  <TableHead>Requirement</TableHead>
                  <TableHead>Met</TableHead>
                  <TableHead>Evidence</TableHead>
                </TableRow>
              </TableHeader>
              <TableBody>
                {result.must_have_coverage.map((entry, i) => (
                  <TableRow key={i}>
                    <TableCell className="font-medium">{entry.requirement}</TableCell>
                    <TableCell className="whitespace-nowrap">{MET_LABELS[entry.met]}</TableCell>
                    <TableCell className="text-muted-foreground">{entry.evidence}</TableCell>
                  </TableRow>
                ))}
              </TableBody>
            </Table>
          </div>
        </section>
      )}
      <List title="Flags" items={result.flags} />
      <AnswerFeedback feedback={result.answer_feedback} questions={questions} />
    </div>
  );
}

const queuedView = (applicationId: string, previous: ScreeningView | null): ScreeningView => ({
  id: previous?.id ?? "",
  application_id: applicationId,
  fit_score: previous?.fit_score ?? null,
  recommendation: previous?.recommendation ?? null,
  result: previous?.result ?? null,
  error_code: null,
  completed_at: previous?.completed_at ?? null,
  updated_at: new Date().toISOString(),
  status: "queued",
});

/**
 * The AI screening of one application (MT-REQ-007, MT-TASK-024): fit score,
 * recommendation, summary, must-have coverage, answer feedback and flags.
 * Polls while the screening is queued or processing, for up to 2 minutes.
 * People aren't colour-coded: everything uses neutral tokens.
 */
export default function ScreeningCard({
  applicationId,
  jobPostId,
  questions,
  screening: initial,
  className,
}: {
  applicationId: string;
  jobPostId: string;
  questions: string[];
  screening: ScreeningView | null;
  className?: string;
}) {
  const [screening, setScreening] = useState(initial);
  const [tick, setTick] = useState(0);
  const [timedOut, setTimedOut] = useState(false);
  const [requeueing, setRequeueing] = useState(false);
  const pollStartedAt = useRef<number | null>(null);
  const { handle: handleEntitlement, dialog } = useEntitlementError();

  const status = screening?.status;
  const inProgress = isScreeningInProgress(status);

  useEffect(() => {
    if (!inProgress) {
      pollStartedAt.current = null;
      return;
    }
    pollStartedAt.current ??= Date.now();
    if (Date.now() - pollStartedAt.current >= SCREENING_POLL_MAX_MS) {
      setTimedOut(true);
      return;
    }

    let cancelled = false;
    const timer = setTimeout(async () => {
      try {
        const res = await fetch(`/api/company/applications/${applicationId}/screening`, {
          cache: "no-store",
        });
        const body = await res.json().catch(() => null);
        if (!cancelled && res.ok && body && "screening" in body) setScreening(body.screening);
      } catch {
        // Try again on the next tick.
      }
      if (!cancelled) setTick((t) => t + 1);
    }, SCREENING_POLL_MS);

    return () => {
      cancelled = true;
      clearTimeout(timer);
    };
  }, [applicationId, inProgress, tick]);

  const requeue = async () => {
    setRequeueing(true);
    try {
      const res = await fetch(`/api/company/job-posts/${jobPostId}/screen`, { method: "POST" });
      if (await handleEntitlement(res)) return;
      const body = await res.json().catch(() => null);
      if (!res.ok) {
        toast.error(body?.error ?? "Couldn't queue the screening. Please try again.");
        return;
      }
      setTimedOut(false);
      pollStartedAt.current = null;
      setScreening((previous) => queuedView(applicationId, previous));
    } catch {
      toast.error("Couldn't queue the screening. Please try again.");
    } finally {
      setRequeueing(false);
    }
  };

  const action = (label: string) => (
    <Button
      type="button"
      variant="outline"
      size="sm"
      onClick={requeue}
      disabled={requeueing}
      className="self-start"
    >
      {requeueing && <Loader2 className="mr-2 h-4 w-4 animate-spin" />}
      {label}
    </Button>
  );

  const showResult = (status === "completed" || status === "stale") && screening?.result;

  return (
    <section
      aria-label="AI screening"
      className={cn("flex flex-col gap-4 rounded-xl border p-4", className)}
    >
      <div className="flex flex-wrap items-center justify-between gap-2">
        <h3 className="text-lg font-semibold tracking-tight">AI screening</h3>
        {showResult && screening?.recommendation && (
          <div className="flex items-center gap-2">
            <MatchScoreBadge score={screening.fit_score} />
            <Badge variant="outline" aria-label="Recommendation">
              {RECOMMENDATION_LABELS[screening.recommendation]}
            </Badge>
          </div>
        )}
      </div>

      {inProgress && (
        <div className="flex flex-col gap-1">
          <p className="flex items-center gap-2 text-sm text-muted-foreground">
            <Loader2 className="h-4 w-4 animate-spin" />
            Screening…
          </p>
          {timedOut && (
            <p className="text-sm text-muted-foreground">
              This is taking longer than usual. Refresh the page to check again.
            </p>
          )}
        </div>
      )}

      {!screening && (
        <>
          <p className="text-sm text-muted-foreground">This application hasn&apos;t been screened yet.</p>
          {action("Screen now")}
        </>
      )}

      {status === "failed" && (
        <>
          <p className="text-sm text-muted-foreground">We couldn&apos;t screen this application.</p>
          {action("Retry")}
        </>
      )}

      {status === "skipped_quota" && (
        <>
          <p className="text-sm text-muted-foreground">
            Your plan&apos;s screenings ran out before this application was screened.
          </p>
          {action("Upgrade to screen")}
        </>
      )}

      {status === "stale" && (
        <div className="flex flex-wrap items-center justify-between gap-3 rounded-lg border bg-muted/40 px-4 py-3">
          <p className="flex items-center gap-2 text-sm">
            <Info className="h-4 w-4 text-muted-foreground" />
            Job changed since this screening.
          </p>
          {action("Re-screen")}
        </div>
      )}

      {showResult && screening?.result && (
        <Result result={screening.result} questions={questions} />
      )}

      {showResult && <p className="text-xs text-muted-foreground">{FOOTNOTE}</p>}
      {dialog}
    </section>
  );
}
